#!/bin/sh
# Writes the /api + /health reverse proxy for nginx, but ONLY when BACKEND_URL is set.
#   docker compose (assignment 3): BACKEND_URL=http://backend:8000 -> proxy on.
#   Cloud Run (assignment 4):      BACKEND_URL empty -> no proxy; the load balancer routes /api.
# Without this, nginx in Cloud Run would point at a host "backend" that does not exist there.
# Runs from the nginx image's /docker-entrypoint.sh, after 20-envsubst-on-templates.sh.
set -eu
out=/etc/nginx/snippets/api-proxy.conf
rm -f "$out"
if [ -z "${BACKEND_URL:-}" ]; then
  echo "40-api-proxy: BACKEND_URL is empty -> no /api proxy (the load balancer routes /api)"
  exit 0
fi
resolver="${NGINX_RESOLVER:-127.0.0.11}"
cat > "$out" <<CONF
# generated by 40-api-proxy.sh (BACKEND_URL=${BACKEND_URL})
# Resolve the backend name at request time (docker DNS), so a restarted backend is found again.
resolver ${resolver} valid=10s ipv6=off;

location /api/ {
    set \$backend "${BACKEND_URL}";
    proxy_pass \$backend;
    proxy_http_version 1.1;
    proxy_set_header Host \$host;
    proxy_set_header X-Real-IP \$remote_addr;
    proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto \$scheme;
    proxy_read_timeout 60s;
    include /etc/nginx/snippets/security-headers.conf;
}

location = /health {
    set \$backend "${BACKEND_URL}";
    proxy_pass \$backend;
    proxy_set_header Host \$host;
    include /etc/nginx/snippets/security-headers.conf;
}
CONF
echo "40-api-proxy: proxying /api and /health to ${BACKEND_URL}"
